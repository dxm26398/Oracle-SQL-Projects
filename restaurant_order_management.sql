-- PART A: CREATE TABLES

-- 1) CUSTOMER

CREATE TABLE CUSTOMER (
  CustomerID  NUMBER(6) PRIMARY KEY,
  FirstName   VARCHAR2(30),
  LastName    VARCHAR2(30),
  Phone       VARCHAR2(20),
  Email       VARCHAR2(60)
);

-- 2) MENU_ITEM

CREATE TABLE EMPLOYEE (
  EmployeeID  NUMBER(6) PRIMARY KEY,
  EmpName     VARCHAR2(50),
  Role        VARCHAR2(30),
  Salary      NUMBER(10,2)
);

-- 3) EMPLOYEE

CREATE TABLE MENU_ITEM (
  ItemID    NUMBER(6) PRIMARY KEY,
  ItemName  VARCHAR2(60),
  Category  VARCHAR2(30),
  Price     NUMBER(8,2)
);


-- 4) ORDERS

CREATE TABLE ORDERS (
  OrderID     NUMBER(8) PRIMARY KEY,
  CustomerID  NUMBER(6),
  EmployeeID  NUMBER(6),
  OrderDate   DATE,
  TotalAmount NUMBER(10,2),
  FOREIGN KEY (CustomerID) REFERENCES CUSTOMER(CustomerID),
  FOREIGN KEY (EmployeeID) REFERENCES EMPLOYEE(EmployeeID)
);


-- 5) ORDER_DETAIL (line items for an order)

CREATE TABLE ORDER_DETAIL (
  OrderID   NUMBER(8),
  ItemID    NUMBER(6),
  Quantity  NUMBER(6),
  PRIMARY KEY (OrderID, ItemID),
  FOREIGN KEY (OrderID) REFERENCES ORDERS(OrderID),
  FOREIGN KEY (ItemID)  REFERENCES MENU_ITEM(ItemID)
);


