SELECT ItemName, Price FROM MENU_ITEM WHERE Price > 10;

-- 2
SELECT c.FirstName || ' ' || c.LastName AS FullName, o.OrderID, o.TotalAmount
FROM CUSTOMER c
JOIN ORDERS o ON o.CustomerID = c.CustomerID
ORDER BY o.TotalAmount DESC;

-- 3
SELECT o.OrderID, e.EmpName, e.Role
FROM ORDERS o
JOIN EMPLOYEE e ON e.EmployeeID = o.EmployeeID;

-- 4
SELECT DISTINCT c.FirstName || ' ' || c.LastName AS CustomerName
FROM CUSTOMER c
JOIN ORDERS o ON o.CustomerID = c.CustomerID
JOIN ORDER_DETAIL od ON od.OrderID = o.OrderID
JOIN MENU_ITEM m ON m.ItemID = od.ItemID
WHERE m.ItemName = 'Chicken Biryani';

-- 5
